# @param {Character[][]} board
# @return {Boolean}
require 'set'
def is_valid_sudoku(board)
  kkk = {}

  (0..8).each do |i|
    k = {}
    kk = {}
    (0..8).each do |j|
      element = board[i][j]
      element2 = board[j][i]
      square_key = (i / 3) * 3 + j / 3
      return false if k.key?(element)
      return false if kk.key?(element2)

      k[element] = 0 if element != '.'
      kk[element2] = 0 if element2 != '.'
      next if element == '.'

      if kkk[square_key].nil?
        kkk[square_key] = Set.new([element]) if element != '.'
      else
        return false if kkk[square_key].include?(element)

        kkk[square_key] << element if element != '.'
      end
    end
  end
  true
end

